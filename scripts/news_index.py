"""Build docs/news_index.md from the news_release entries in every data/raw/<TICKER>/manifest.yaml.

Tags are keyword rules (a first cut for the future news feed), not model judgments.
Usage: uv run python scripts/news_index.py
"""

import re
from pathlib import Path

import yaml

TAGS = [  # (tag, pattern) checked against the title, in order; a release can carry several
    (
        "Funding",
        r"\$[0-9.]+ ?million|financ|placement|offering|bookbuild|tranche|debenture|funding|"
        r"grant(?! of (stock|deferred|long|equity))|repays|debt",
    ),
    ("Deal", r"sale of|sells|acqui|agreement|framework|offtake|strategic|divest|joint venture"),
    (
        "Study",
        r"feasibility|pfs|pea|economic assessment|technical report|resource estimate|"
        r"\bmre\b|mine plan",
    ),
    ("Permits", r"permit|environmental|reclamation|approval|critical minerals office"),
    ("Drilling", r"drill|assay|intersect|step-out|grading|high-grade|sulphide|bornite|extends"),
    ("Production", r"commercial production|first copper|production"),
    ("Listing", r"nyse|nasdaq|asx|listing|trading|consolidation|index"),
    ("People", r"appoint|director|board|cfo|ceo|coo|passing|leadership|team"),
]


def tags(title: str) -> str:
    found = [t for t, rx in TAGS if re.search(rx, title, re.I)]
    return ", ".join(found) or "Other"


def main() -> None:
    lines = [
        "# News index",
        "",
        "Generated by `scripts/news_index.py` from the manifests; do not edit by hand.",
        "Window: what has been collected (currently 2025-11-11 to 2026-11-11).",
        "Tags are keyword rules, not judgments.",
        "",
    ]
    for manifest in sorted(Path("data/raw").glob("*/manifest.yaml")):
        m = yaml.safe_load(manifest.read_text())
        news = sorted(
            (d for d in m["documents"] if d["type"] == "news_release"),
            key=lambda d: str(d["filing_date"]),
            reverse=True,
        )
        if not news:
            continue
        lines += [f"## {m['ticker']}: {m['name']} ({len(news)})", "", "| Date | Tags | Release |"]
        lines.append("|---|---|---|")
        for d in news:
            title = d["title"].replace("|", "/")
            link = f"[{title}]({d['url']})" if d.get("url") else title
            lines.append(f"| {d['filing_date']} | {tags(d['title'])} | {link} |")
        lines.append("")
    Path("docs/news_index.md").write_text("\n".join(lines))
    print("wrote docs/news_index.md")


if __name__ == "__main__":
    main()
